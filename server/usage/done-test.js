// Chạy: node server/usage/done-test.js  (dùng thư mục tạm, không đụng log / cấu hình thật)
const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'devdeck-done-'))
process.env.DEVDECK_DATA = path.join(tmp, 'data')
process.env.CLAUDE_CONFIG_DIR = path.join(tmp, 'claude')
process.env.CODEX_HOME = path.join(tmp, 'codex')
process.env.GEMINI_DIR = path.join(tmp, 'gemini')
process.env.ANTIGRAVITY_DIR = path.join(tmp, 'agy')

const cfg = require('./notify-config')
const done = require('./done')
const hook = require('./claude-hook')
const claude = require('./claude')
const codex = require('./codex')
const gemini = require('./gemini')
const agy = require('./antigravity')

// ---- cấu hình: quy tắc theo thư mục, dài nhất thắng ----
const c = cfg.sanitize({ rules: [{ path: '/work', enabled: false }, { path: '/work/app/', enabled: true }, { path: 'C:\\Dev\\x', enabled: false }] }, true)
const ok = (projectPath, extra) => cfg.allows(c, { source: 'claude', projectPath, durationSec: 100, ...extra })
assert.strictEqual(ok('/work/other'), false, 'thư mục cha tắt')
assert.strictEqual(ok('/work/app/src'), true, 'quy tắc con dài hơn thắng')
assert.strictEqual(ok('/work/app2'), false, '/work/app2 không khớp nhầm /work/app, rơi vào /work → tắt')
assert.strictEqual(ok('/work2'), true, '/work2 không thuộc /work')
assert.strictEqual(ok('c:/dev/X/sub'), false, 'khác hoa thường và dấu gạch vẫn khớp')
assert.strictEqual(ok(''), true, 'không có đường dẫn theo công tắc chung')
assert.strictEqual(ok('/p', { durationSec: 5 }), false, 'dưới ngưỡng 30s')
assert.strictEqual(ok('/p', { durationSec: null }), true, 'không biết thời gian thì không chặn')
assert.strictEqual(cfg.allows({ ...c, enabled: false }, { source: 'claude', projectPath: '', durationSec: 100 }), false)
assert.strictEqual(cfg.allows({ ...c, sources: { ...c.sources, codex: false } }, { source: 'codex', projectPath: '', durationSec: 100 }), false)
assert.throws(() => cfg.sanitize({ rules: [{ path: 'relative', enabled: true }] }, true), /tuyệt đối/)
assert.throws(() => cfg.sanitize({ minSeconds: -1 }, true))
assert.throws(() => cfg.sanitize({ rules: Array.from({ length: 201 }, (_, i) => ({ path: '/p' + i, enabled: true })) }, true))
assert.deepStrictEqual(cfg.load().rules, [], 'chưa có file thì mặc định bật tất cả')
assert.strictEqual(cfg.load().enabled, true)

// ---- adapter: nhận biết lượt đã xong ----
const J = (...a) => a.map((o) => JSON.stringify(o)).join('\n')
assert.strictEqual(!!claude.isDone(J({ type: 'user' }, { type: 'assistant', message: { content: [{ type: 'text', text: 'ok' }] } }, { type: 'system' })), true)
assert.strictEqual(!!claude.isDone(J({ type: 'assistant', message: { content: [{ type: 'tool_use' }] } })), false, 'đang chờ tool')
assert.strictEqual(!!claude.isDone(J({ type: 'assistant', message: { content: [] } }, { type: 'user' })), false, 'người dùng nói sau cùng')
assert.strictEqual(!!claude.isDone(J({ type: 'assistant', isSidechain: true, message: { content: [] } })), false, 'subagent không tính')
assert.strictEqual(!!claude.isDone('{"cắt dở'), false)
assert.strictEqual(!!codex.isDone(J({ type: 'event_msg', payload: { type: 'task_complete' } }, { type: 'event_msg', payload: { type: 'token_count' } })), true)
assert.strictEqual(!!codex.isDone(J({ type: 'response_item', payload: { type: 'function_call' } })), false)
assert.strictEqual(!!codex.isDone(J({ type: 'response_item', payload: { type: 'message', role: 'assistant' } })), true)
assert.strictEqual(!!gemini.isDone(JSON.stringify({ messages: [{ type: 'user' }, { type: 'gemini', content: 'x' }] }), 'a.json'), true)
assert.strictEqual(!!gemini.isDone(JSON.stringify({ messages: [{ type: 'gemini', toolCalls: [{ name: 'ls' }] }] }), 'a.json'), false)
assert.strictEqual(!!gemini.isDone(J({ type: 'user' }, { type: 'gemini' }), 'a.jsonl'), true)
assert.strictEqual(!!agy.isDone(J({ type: 'USER_INPUT' }, { type: 'PLANNER_RESPONSE', status: 'DONE' })), true)
assert.strictEqual(!!agy.isDone(J({ type: 'PLANNER_RESPONSE', status: 'GENERATING' })), false)
assert.strictEqual(!!agy.isDone(J({ type: 'PLANNER_RESPONSE', status: 'DONE' }, { type: 'RUN_COMMAND' })), false)

// ---- watcher: seed → đổi → ngừng đổi → báo đúng 1 lần ----
const dir = path.join(tmp, 'claude', 'projects', 'proj')
fs.mkdirSync(dir, { recursive: true })
const file = path.join(dir, 's1.jsonl')
const line = (type, content, extra) => JSON.stringify({ type, cwd: '/work/app', timestamp: '2026-01-01T00:00:00Z', message: { id: 'm' + Math.random(), model: 'x', usage: { input_tokens: 1, output_tokens: 1 }, content }, ...extra }) + '\n'
const touch = (f, sec) => { const t = new Date(Date.now() + sec * 1000); fs.utimesSync(f, t, t) }
fs.writeFileSync(file, line('assistant', [{ type: 'text', text: 'cũ' }]))
cfg.save({ minSeconds: 0, debounceSeconds: 8 })
const t0 = Date.now()
done.tick(t0)
assert.strictEqual(done.since(0).events.length, 0, 'lần đầu chỉ ghi nhận, không báo việc cũ')

fs.appendFileSync(file, line('user', 'hỏi'))
fs.appendFileSync(file, line('assistant', [{ type: 'tool_use' }]))
touch(file, 1)
done.tick(t0 + 4000) // thấy file đổi (nhịp 15s mới liệt kê lại → ép bằng reset thời gian)
done.tick(t0 + 20000)
done.tick(t0 + 30000)
assert.strictEqual(done.since(0).events.length, 0, 'cuối log là tool_use nên chưa xong')

fs.appendFileSync(file, line('assistant', [{ type: 'text', text: 'xong' }]))
touch(file, 2)
done.tick(t0 + 40000)
done.tick(t0 + 41000) // log vừa đổi, chưa đủ debounce
assert.strictEqual(done.since(0).events.length, 0, 'chưa ngừng đổi đủ lâu')
done.tick(t0 + 50000)
let ev = done.since(0).events
assert.strictEqual(ev.length, 1)
assert.deepStrictEqual([ev[0].source, ev[0].projectPath, ev[0].project, ev[0].session], ['claude', '/work/app', 'app', 's1'])
done.tick(t0 + 70000)
assert.strictEqual(done.since(0).events.length, 1, 'không báo lặp')
assert.strictEqual(done.since(ev[0].id).events.length, 0)

// dòng system ghi thêm sau lời đáp đã báo → không báo lại
fs.appendFileSync(file, JSON.stringify({ type: 'system', subtype: 'turn_duration' }) + '\n')
touch(file, 2.5)
done.tick(t0 + 60000); done.tick(t0 + 75000)
assert.strictEqual(done.since(0).events.length, 1, 'chỉ có dòng system mới thì không báo lại')

// thư mục bị tắt → không có sự kiện
cfg.save({ minSeconds: 0, rules: [{ path: '/work', enabled: false }] })
fs.appendFileSync(file, line('assistant', [{ type: 'text', text: 'lại xong' }]))
touch(file, 3)
done.tick(t0 + 80000); done.tick(t0 + 100000)
assert.strictEqual(done.since(0).events.length, 1, 'repo bị tắt thì không báo')

// ---- hook Stop ----
cfg.save({ minSeconds: 0 })
done.reset()
assert.strictEqual(hook.tokenOk('sai'), false, 'chưa có token thì từ chối')
const claudeDir = path.join(tmp, 'claude')
const settings = path.join(claudeDir, 'settings.json')
const mine = { hooks: { Stop: [{ hooks: [{ type: 'command', command: 'echo hi' }] }], PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: 'true' }] }] }, theme: 'dark' }
fs.writeFileSync(settings, JSON.stringify(mine))
hook.install(claudeDir, 4317)
let s = JSON.parse(fs.readFileSync(settings, 'utf8'))
assert.strictEqual(s.hooks.Stop.length, 2, 'giữ hook của người dùng, thêm hook của DevDeck')
assert.strictEqual(s.theme, 'dark')
assert.ok(fs.existsSync(settings + '.devdeck-bak'), 'sao lưu bản gốc')
assert.deepStrictEqual(JSON.parse(fs.readFileSync(settings + '.devdeck-bak', 'utf8')), mine)
hook.install(claudeDir, 4317)
assert.strictEqual(JSON.parse(fs.readFileSync(settings, 'utf8')).hooks.Stop.length, 2, 'cài lại không nhân đôi')
const st = hook.status(4317).find((x) => x.dir === '')
assert.deepStrictEqual([st.installed, st.stale], [true, false])
assert.strictEqual(hook.status(5000).find((x) => x.dir === '').stale, true, 'lệch cổng → cần cài lại')
const tok = fs.readFileSync(path.join(tmp, 'data', 'ai-hook-token'), 'utf8').trim()
assert.strictEqual(hook.tokenOk(tok), true)
assert.strictEqual(hook.tokenOk(tok.slice(1) + 'x'), false)
hook.uninstall(claudeDir)
assert.deepStrictEqual(JSON.parse(fs.readFileSync(settings, 'utf8')), mine, 'gỡ xong về như cũ')
fs.writeFileSync(settings, '{hỏng')
assert.throws(() => hook.install(claudeDir, 4317), /không phải JSON/)
assert.strictEqual(fs.readFileSync(settings, 'utf8'), '{hỏng', 'không ghi đè file hỏng')

// payload hook: transcript ngoài thư mục log bị bỏ qua, còn cwd vẫn dùng được
const outside = path.join(tmp, 'evil.jsonl')
fs.writeFileSync(outside, line('user', 'x', { timestamp: '2000-01-01T00:00:00Z' }))
const e1 = done.fromHook({ session_id: 'abc', cwd: '/work2/z', transcript_path: outside }, Date.parse('2026-01-01T00:10:00Z'))
assert.strictEqual(e1.durationSec, null)
assert.strictEqual(e1.projectPath, '/work2/z')
assert.strictEqual(done.fromHook({ session_id: 'abc', cwd: '/work2/z' }, Date.parse('2026-01-01T00:10:01Z')), null, 'bỏ trùng cùng phiên trong 3s')
const tr = path.join(dir, 'h.jsonl')
fs.writeFileSync(tr, line('user', 'câu hỏi', { timestamp: '2026-01-01T00:00:00Z' }) + line('assistant', [{ type: 'tool_use' }], { timestamp: '2026-01-01T00:01:00Z' }) + line('user', [{ type: 'tool_result' }], { timestamp: '2026-01-01T00:01:30Z' }))
assert.strictEqual(done.fromHook({ session_id: 'def', cwd: '/q', transcript_path: tr }, Date.parse('2026-01-01T00:02:00Z')).durationSec, 120, 'tính từ câu hỏi thật, bỏ tool_result')
assert.doesNotThrow(() => done.fromHook('rác'), 'payload lạ không ném lỗi')

fs.rmSync(tmp, { recursive: true, force: true })
console.log('ok ai done')
